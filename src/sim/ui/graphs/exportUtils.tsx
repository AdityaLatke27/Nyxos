import { SOURCE_EXPLAIN, SOURCE_SHORT, type Source } from '../../../analysis/provenance'

export const FRAME_NOTE = 'Frame: planetocentric latitude, east-positive longitude, mean-Earth/polar-axis (IAU 2009); heights above the 1737.4 km reference sphere (LOLA).'

/** Downloads a CSV with # comment lines at the top that record where the numbers came from. */
export function downloadCsv(filename: string, meta: string[], header: string[], rows: (string | number)[][]) {
  const esc = (v: string | number) => {
    const s = typeof v === 'number' ? (Number.isInteger(v) ? String(v) : String(+v.toFixed(6))) : v
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
  }
  const lines = [
    ...meta.map((m) => `# ${m}`),
    `# Generated by NYXOS ${new Date().toISOString()}`,
    header.join(','),
    ...rows.map((r) => r.map(esc).join(',')),
  ]
  const url = URL.createObjectURL(new Blob([lines.join('\n') + '\n'], { type: 'text/csv;charset=utf-8' }))
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 2000)
}

export function Chip({ source }: { source: Source }) {
  return (
    <abbr className={`src src-${source}`} title={SOURCE_EXPLAIN[source]}>
      {SOURCE_SHORT[source]}
    </abbr>
  )
}

export function ExportButton({ onClick, disabled }: { onClick: () => void; disabled?: boolean }) {
  return (
    <button className="btn gd-export" onClick={onClick} disabled={disabled} title="Download the plotted data as CSV, with source and method in the header">
      Export CSV
    </button>
  )
}

